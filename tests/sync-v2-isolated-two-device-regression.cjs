'use strict';
// Isolated two-device regression; never connects to the owner's Supabase project.
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const source=fs.readFileSync('sync-v2-reconcile.js','utf8');
const context={};vm.runInNewContext(source,context,{filename:'sync-v2-reconcile.js'});
const {planWithBaseline,threeWay}=context.MCReconcileV2;
const record=(id,extra={})=>({id,title:'Prueba aislada',publisher:'Editorial ficticia',series:'Serie ficticia',issue:'1',...extra});
const base=record('test-device-a');
const local=record(base.id,{title:'Edición A'});
const remote=record(base.id,{synopsis:'Edición B'});
const plan=planWithBaseline([base],[local],[remote]);
assert.equal(plan.conflicts.length,0,'independent edits must not conflict');
assert.equal(plan.merged.length,1);
assert.equal(plan.merged[0].record.title,'Edición A');
assert.equal(plan.merged[0].record.synopsis,'Edición B');
const collision=planWithBaseline([base],[record(base.id,{title:'A'})],[record(base.id,{title:'B'})]);
assert.equal(collision.conflicts[0].reason,'concurrent-field-edits');
assert.equal(collision.upload.length+collision.download.length+collision.merged.length,0,'conflicts must block writes');
const missing=planWithBaseline([base],[base],[]);
assert.equal(missing.conflicts[0].reason,'missing-record-without-tombstone');
assert.equal(missing.upload.length,0);
const protectedCover=threeWay(record('cover',{coverKey:'private/a'}),record('cover',{coverKey:''}),record('cover',{coverKey:'private/a'}));
assert.equal(protectedCover.reason,'protected-cover-cleared');
const deleted=planWithBaseline([base],[{...base,deleted:true,deletedAt:'2026-11-15T09:00:00Z'}],[{...base,title:'Edited elsewhere'}]);
assert.equal(deleted.conflicts[0].reason,'delete-versus-edit');
const newCover=threeWay(record('new-cover'),record('new-cover',{coverKey:'uid/cover-a'}),record('new-cover'));
assert.equal(newCover.reason,'cover-reference-added-unverified','new private cover references require verified binary transfer');
const newCoverUrl=threeWay(record('new-url'),record('new-url'),record('new-url',{coverUrl:'https://example.invalid/image.jpg'}));
assert.equal(newCoverUrl.reason,'cover-reference-added-unverified','remote cover URL must not be trusted without binary verification');
const safeText=threeWay(record('text-only'),record('text-only',{title:'Changed'}),record('text-only'));
assert.equal(safeText.status,'merged','ordinary metadata changes remain reconcilable');
// No baseline: never propagate a new row that references an unverified private cover.
const firstCoverUpload=planWithBaseline([],[record('fresh-upload',{coverKey:'uid/private.jpg'})],[]);
assert.equal(firstCoverUpload.conflicts[0].reason,'new-record-cover-unverified');
assert.equal(firstCoverUpload.upload.length,0);
const firstCoverDownload=planWithBaseline([],[],[record('fresh-download',{coverUrl:'https://example.invalid/cover.jpg'})]);
assert.equal(firstCoverDownload.conflicts[0].reason,'new-record-cover-unverified');
assert.equal(firstCoverDownload.download.length,0);
const firstTextOnly=planWithBaseline([],[record('fresh-text')],[]);
assert.equal(firstTextOnly.conflicts.length,0);
assert.equal(firstTextOnly.upload.length,1,'new metadata-only records remain plannable');
const mixedBatch=planWithBaseline([],[record('safe'),record('unsafe',{coverKey:'uid/private.jpg'})],[]);
assert.equal(mixedBatch.conflicts[0].reason,'new-record-cover-unverified');
assert.equal(mixedBatch.upload.length,0,'any unverified cover blocks the entire batch');
// Identical cover references on two devices do not prove the binary exists.
const sameUnverified=planWithBaseline([],[record('same-cover',{coverKey:'uid/same.jpg'})],[record('same-cover',{coverKey:'uid/same.jpg'})]);
assert.equal(sameUnverified.conflicts[0].reason,'new-record-cover-unverified');
assert.equal(sameUnverified.unchanged.length,0,'unverified identical covers must not be acknowledged');
const differingUnverified=planWithBaseline([],[record('different-cover',{coverKey:'uid/a.jpg'})],[record('different-cover',{coverKey:'uid/b.jpg'})]);
assert.equal(differingUnverified.conflicts[0].reason,'new-record-cover-unverified');
const sameText=planWithBaseline([],[record('same-text')],[record('same-text')]);
assert.equal(sameText.conflicts.length,0);
assert.equal(sameText.unchanged.length,1);
console.log('PASS: isolated two-device merge, conflict, pagination gap, cover protection and tombstone');
