'use strict';
const assert=require('node:assert/strict');
const {plan}=require('../sync-v2-baseline-plan.js');
const row={id:'comic-1',title:'Original',coverKey:'private-cover-1'};
const base=[row];
const missing=plan({local:[],remote:[],baseline:base});
assert.equal(missing.safeToExecute,false);
assert.deepEqual(missing.upload,[]);
assert.deepEqual(missing.download,[]);
assert.deepEqual(missing.conflicts,[{id:'comic-1',reason:'missing-on-both-sides-without-tombstone'}]);
const untouched=plan({local:base,remote:base,baseline:base});
assert.deepEqual(untouched.identical,['comic-1']);
assert.equal(untouched.conflicts.length,0);
const unilateral=plan({local:[],remote:base,baseline:base});
assert.equal(unilateral.conflicts[0]?.reason,'missing-without-tombstone');
const tombstone=plan({local:[],remote:[],baseline:base,tombstones:[{id:'comic-1',explicit:true,baseHash:'a'.repeat(64)}]});
assert.deepEqual(tombstone.deletionsBlocked,['comic-1']);
assert.equal(tombstone.safeToExecute,false);
console.log('PASS baseline double-missing, unilateral-missing and tombstone fail-closed');
